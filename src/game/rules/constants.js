/**
 * 全局常量
 * ------------------------------------------------------------------
 * 单独成一个文件，是为了打破模块之间的循环依赖：
 * guardians 要用 BASE_STATS，stats 要用 RELICS，legacy 要用 PLAYER_HP——
 * 如果这些常量住在各自的模块里，三者会绕成一个环，
 * Node 的循环 require 只会给出半初始化的对象，非常难查。
 *
 * v4.0 又多了两条「命线」（饱食 / 精神）和万物阁的启动资源，
 * 它们被 survival / facilities / run 三个模块同时读，放这里最省事。
 */

/** 旅人的体力上限 */
const PLAYER_HP = 100;

/**
 * 旅人的初始数值。
 * mana 给 42 而不是 30：自带的两道咒（涌泉 35 / 焚天 40）一开始就能念出来，
 * 否则玩家点开咒术槽发现一个都放不了，麦克风这个卖点等于没演示到。
 */
const BASE_STATS = { atk: 10, def: 4, crit: 0.05, mana: 42 };

/* ══════════════════════════════════════════════════════════════
   v4.0 生存两条线
   ──────────────────────────────────────────────────────────────
   肉鸽的压力不该只来自敌人，更该来自「你还撑得住几天」。
   饱食管身体，精神管脑子，两条都归零就活不到下一次天亮。
   ══════════════════════════════════════════════════════════════ */

/** 饱食上限。每走一格 / 每打一回合都在掉，归零后每步掉体力 */
const SATIETY_MAX = 100;

/** 精神上限。遇妖、见血、夜里的威压都在掉，见底会「失魂」 */
const SANITY_MAX = 100;

/** 开局兜里的铜钱。够建第一间设施，或者买两顿饭 */
const START_COIN = 40;

/**
 * 香火：献祭的硬成本。
 * 开局带 3 炷，之后只能靠经营攒（神龛、歇脚处、箱笼、阁里买）。
 * 没有它，献祭就变成"无限次免费攻击"，装备和精怪都会失去意义。
 */
const START_INCENSE = 3;
/** 香火基础上限，祭坛每级 +2 */
const INCENSE_BASE = 6;

/** 货仓的基础容量（格）。货仓每升一级 +4 */
const STORE_BASE = 6;

/** 迷宫边长。5×5 = 25 个房间，走完大约十步，刚好是一天能承受的长度 */
const MAZE_SIZE = 5;

module.exports = {
  PLAYER_HP,
  BASE_STATS,
  SATIETY_MAX,
  SANITY_MAX,
  START_COIN,
  START_INCENSE,
  INCENSE_BASE,
  STORE_BASE,
  MAZE_SIZE,
};
